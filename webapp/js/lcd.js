export function glyph(ch) {
  const c = ch.toUpperCase();
  if (c >= "0" && c <= "9") return BASE[c.charCodeAt(0) - 48];
  if (c >= "A" && c <= "Z") return BASE[10 + c.charCodeAt(0) - 65];
  return EXTRA[c] || [0x7f, 0x41, 0x41, 0x41, 0x7f];
}

const NS = "http://www.w3.org/2000/svg";
export class Lcd {
  constructor(svg, cols = 16, rows = 2) {
    this.svg = svg; this.cols = cols; this.rows = rows; this.lines = Array(rows).fill("");
    const cw = 6, ch = 9;
    svg.setAttribute("viewBox", `-1.5 -1.5 ${cols * cw + 2} ${rows * ch + 2}`);
    svg.setAttribute("role", "img");
    this.cells = [];
    for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
      const g = document.createElementNS(NS, "g");
      g.setAttribute("transform", `translate(${c * cw} ${r * ch})`);
      const dots = [];
      for (let x = 0; x < 5; x++) for (let y = 0; y < 7; y++) {
        const d = document.createElementNS(NS, "rect");
        d.setAttribute("x", x); d.setAttribute("y", y); d.setAttribute("width", 0.84); d.setAttribute("height", 0.84);
        d.setAttribute("class", "px"); g.append(d); dots.push(d);
      }
      svg.append(g); this.cells.push(dots);
    }
  }
  show(...lines) {
    for (let r = 0; r < this.rows; r++) {
      const text = String(lines[r] ?? "").padEnd(this.cols).slice(0, this.cols);
      if (text === this.lines[r]) continue;
      this.lines[r] = text;
      for (let c = 0; c < this.cols; c++) {
        const g = glyph(text[c]), dots = this.cells[r * this.cols + c];
        for (let x = 0; x < 5; x++) for (let y = 0; y < 7; y++) dots[x * 7 + y].classList.toggle("on", Boolean((g[x] >> y) & 1));
      }
    }
    this.svg.setAttribute("aria-label", this.lines.map((l) => l.trim()).join(" / "));
  }
}
